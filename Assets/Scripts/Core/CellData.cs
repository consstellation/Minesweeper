using UnityEngine;

public class CellData
{
    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\
    /// <summary>
    /// показывает, есть ли мина в клетке
    /// </summary>
    public bool IsMine {  get; private set; }

    /// <summary>
    /// показывает, открыта ли клетка
    /// </summary>
    /// 
    public bool IsOpen { get; private set; }
    /// <summary>
    /// показывает, установлен ли флаг
    /// </summary>
    /// 
    public bool IsFlagged { get; private set; }
    /// <summary>
    /// Хранит количество мин вокруг клетки
    /// </summary>
    public int CountAroundMine { get; private set; }

    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\
    /// <summary>
    /// устанавливает мину в клетку
    /// </summary>
    public void PlaceMine()
    {
        IsMine = true;
    }
    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\
    /// <summary>
    /// открывает клетку если это разрешено
    /// </summary>
    public void Open()
    {
        if (!IsMine && !IsFlagged && !IsOpen)
            IsOpen = true;
    }
    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\
    /// <summary>
    /// устанавливает/снимает флаг
    /// </summary>
    public void ToggleFlag()
    {
        if(!IsOpen)
            IsFlagged = !IsFlagged;
    }
    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\
    /// <summary>
    /// сохраняет количество мин вокруг клетки
    /// </summary>
    /// <param name="count"></param>
    public void SetAdjacentMines(int count)
    {
        if (count < 0)
            return;

        CountAroundMine = count;

    }
    //------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------\\

}
